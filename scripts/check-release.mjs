import fs from 'node:fs/promises'
const required = [
  'release-evidence/code-license.json',
  'release-evidence/bible-license.json',
  'release-evidence/platform-acceptance.json',
]
for (const file of required) {
  let evidence
  try {
    evidence = JSON.parse(await fs.readFile(file, 'utf8'))
  } catch {
    throw new Error(
      `Release evidence required: ${file}. See THIRD_PARTY_NOTICES.md and docs/operations/release-checklist.md.`,
    )
  }
  if (
    evidence.approved !== true ||
    !evidence.approvedBy ||
    !evidence.source ||
    !evidence.reviewedAt
  )
    throw new Error(`Incomplete release evidence: ${file}`)
}
if (process.platform === 'darwin' && !process.env.CSC_LINK && !process.env.CSC_NAME)
  throw new Error('A distribution signing identity must be configured for a release build.')
console.log(
  'Release evidence verified. Credentials and license grants are not generated by this check.',
)
